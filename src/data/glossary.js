/** รหัสคำศัพท์ที่ป้ายสถานะดาวควรลิงก์ไป */
export function dignityTermId(dignity) {
  if (!dignity) return null;
  if (dignity.type === 'own') return 'own';
  if (dignity.type === 'exalt') return dignity.great ? 'great-exalt' : 'exalt';
  return dignity.great ? 'great-debil' : 'debil';
}

/** ค้นหาในคำศัพท์ (ชื่อ อังกฤษ คำอธิบายสั้น และรายละเอียด) และกรองตามหมวด */
export function searchGlossary(query = '', category = 'all') {
  const q = query.trim().toLowerCase();
  return GLOSSARY.filter((g) => {
    if (category !== 'all' && g.category !== category) return false;
    if (!q) return true;
    return [g.term, g.en, g.short, g.detail].some((t) => t.toLowerCase().includes(q));
  });
}
